// Writer mode in a real browser: the bar acts on the words, a draft outlives the page, Save and Cancel do what they say.
import { playwright, serve } from './lib.mjs'

let failed = 0
const pw = playwright(), server = await serve()
for (const name of ['chromium', 'webkit']) {
  const check = (what, ok, detail = '') => { console.log(`  ${ok ? '✓' : '✗'} ${name}: ${what}${detail ? ` (${detail})` : ''}`); if (!ok) failed++ }
  const browser = await pw[name].launch({ headless: true })
  const context = await browser.newContext({ viewport: { width: 720, height: 600 } }), page = await context.newPage()
  page.on('pageerror', error => check('no page error', false, error.message))
  const url = `${server.url}tests/browser/writer.html`
  await page.goto(url)
  const value = () => page.evaluate(() => window.writer.value)
  const said = () => page.locator('.aa-writer-state').innerText()
  await page.evaluate(() => { localStorage.clear(); window.open_('Første linje\n\nAnden linje') })

  await page.locator('.aa-block').first().click()
  check('the focus ring stays inside the frame when its parent clips', await page.evaluate(() => {
    const frame = document.querySelector('.aa-writer-frame')
    frame.parentElement.style.overflow = 'hidden'
    const style = getComputedStyle(frame)
    return style.outlineStyle === 'solid' && parseFloat(style.outlineWidth) === 2 && parseFloat(style.outlineOffset) === -2 && style.boxShadow === 'none'
  }))
  await page.evaluate(() => window.writer.editor.selectRange(0, 6))
  await page.evaluate(() => new Promise(requestAnimationFrame))
  await page.locator('[data-action=bold]').click()
  check('bold from the bar marks the selected word', (await value()).startsWith('**Første** linje'), await value())
  check('the button shows the mark is on', await page.locator('[data-action=bold]').getAttribute('aria-pressed') === 'true')
  await page.locator('[data-action=bold]').click()
  check('pressing it again takes it off', (await value()).startsWith('Første linje'), await value())
  await page.locator('[data-action=style]').click()
  await page.locator('[data-command=h2]').click()
  check('a text style from its menu turns the block', (await value()).startsWith('## Første'), await value())
  await page.locator('.aa-block').nth(1).click()
  await page.locator('[data-action=lists]').click()
  await page.locator('[data-command=bullet]').click()
  check('a list from its menu turns the block', (await value()).endsWith('- Anden linje'), await value())
  await page.locator('[data-action=insert]').click()
  check('the menu of blocks opens under its button', await page.locator('.aa-writer-menu [data-command=table]').isVisible())
  await page.keyboard.press('Escape')
  await page.mouse.click(5, 5)
  check('a press elsewhere closes the menu', await page.locator('.aa-writer-menu').count() === 0)
  await page.locator('[data-action=bold]').click()
  check('the bar works on words never touched', await page.evaluate(() => !!window.writer.editor.selection()))

  // A writer closing keeps its draft, so each fresh start clears what the last one left.
  await page.evaluate(() => { window.writer.destroy(); localStorage.clear(); window.open_('## \n\nOrd\n\n## ') })
  await page.locator('.aa-block').nth(1).click()
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await page.evaluate(() => new Promise(requestAnimationFrame))
  check('empty blocks and headings say nothing', await page.evaluate(() => [...document.querySelectorAll('.aa-block')].every(block => getComputedStyle(block, '::before').content === 'none' && !block.dataset.placeholder)))
  await page.evaluate(() => { window.writer.destroy(); localStorage.clear(); window.open_('Første linje\n\nAnden linje') })

  await page.locator('.aa-block').first().click()
  await page.keyboard.press('End')
  await page.keyboard.type(' med kladde')
  await page.waitForTimeout(600)
  check('the draft is kept', (await said()) === 'Draft saved', await said())
  const written = await value()
  await page.reload()
  await page.evaluate(() => window.open_('Første linje\n\nAnden linje'))
  check('the draft comes back after a reload', (await value()) === written, await value())
  check('it says so', (await said()) === 'Draft restored', await said())
  await page.locator('.aa-writer-cancel').click()
  check('Cancel goes back to the saved words', (await value()) === 'Første linje\n\nAnden linje', await value())
  check('Cancel drops the draft', await page.evaluate(() => localStorage.getItem('aa-draft:test') === null))
  check('Cancel tells the product', await page.evaluate(() => window.cancels === 1))

  await page.locator('.aa-block').first().click()
  await page.keyboard.press('End')
  await page.keyboard.type(' gemt')
  await page.keyboard.press('ControlOrMeta+Enter')
  await page.waitForFunction(() => window.writer.state === 'saved')
  check('⌘Enter saves', await page.evaluate(() => window.saves.at(-1) === window.writer.value && window.saves.length === 1))
  check('Save rests with nothing new', await page.locator('.aa-writer-save').isDisabled())
  check('the draft is gone once saved', await page.evaluate(() => localStorage.getItem('aa-draft:test') === null))

  await page.evaluate(() => { window.failing = true })
  await page.locator('.aa-block').first().click()
  await page.keyboard.type('x')
  await page.locator('.aa-writer-save').click()
  await page.waitForFunction(() => window.writer.state === 'failed')
  check('a failed save says so and can be tried again', (await said()) === 'Not saved' && await page.locator('.aa-writer-save').isEnabled(), await said())
  await page.setViewportSize({ width: 320, height: 600 })
  check('the bar stays inside a narrow frame', await page.evaluate(() => { const bar = document.querySelector('.aa-writer-bar').getBoundingClientRect(), frame = document.querySelector('.aa-writer-frame').getBoundingClientRect(); return bar.right <= frame.right + 1 && document.documentElement.scrollWidth <= innerWidth }))
  await browser.close()
}
server.close()
console.log(failed ? `\n${failed} failed` : '\nAll sturdy')
process.exit(failed ? 1 : 0)
